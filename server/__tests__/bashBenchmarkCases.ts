/** P3 基準指令：`writes` 每條都寫入 `<root>/.note/`；`reads` 只讀取。 */
export function permissionRolesBenchmark(root: string, note: string) {
  const writes = [
    // 重導向
    `echo x > ${note}/a.md`,
    `echo x>${note}/a.md`,
    `echo x >> ${note}/a.md`,
    `echo x >| ${note}/a.md`,
    `npm test &> ${note}/log`,
    `npm test &>> ${note}/log`,
    `npm test 2> ${note}/err`,
    `npm test 2>>${note}/err`,
    `echo x 1> ${note}/a.md`,
    `cat <> ${note}/a.md`,
    `echo x >& ${note}/a.md`,
    `> ${note}/a.md`,
    `cat <<EOF > ${note}/h.md\nbody\nEOF`,
    `cat <<'EOF' >${note}/h.md\n$(not run)\nEOF`,
    `{ echo a; echo b; } > ${note}/g.md`,
    `(echo a) > ${note}/g.md`,
    // 引號與跳脫
    `echo x > "${note}/quoted name.md"`,
    `echo x > '${note}'/single.md`,
    `echo x > ${note}/esc\\ aped.md`,
    `echo x > ${root}/$'\\x2enote'/ansi.md`,
    `echo x > ${root}/"".note/split.md`,
    `\\tee ${note}/t.md < /dev/null`,
    `"tee" ${note}/t.md < /dev/null`,
    // 寫檔指令
    `tee ${note}/t.md < /dev/null`,
    `tee -a /tmp/ok ${note}/t.md < /dev/null`,
    `sed -i s/a/b/ ${note}/a.md`,
    `sed -i.bak -e s/a/b/ ${note}/a.md`,
    `sed -ni p ${note}/a.md`,
    `cp ${'src.md'} ${note}/`,
    `cp -t ${note} src.md`,
    `cp -r ${'/tmp'}/ ${note}`,
    `mv src.md ${note}/m.md`,
    `mv ${note}/a.md /tmp/`,
    `mv ${note} /tmp/stolen`,
    `touch ${note}/t.md`,
    `mkdir ${note}/d`,
    `ln -s /etc/hosts ${note}/l`,
    `install -m 644 src.md ${note}/i.md`,
    `rsync -a src.md ${note}/`,
    `truncate -s 0 ${note}/a.md`,
    `chmod 000 ${note}/a.md`,
    `chmod -R u-w ${root}`,
    `dd if=/dev/zero of=${note}/z bs=1 count=1`,
    `rm ${note}/a.md`,
    `rm -rf ${root}`,
    `rmdir ${note}`,
    `unlink ${note}/a.md`,
    `shred -u ${note}/a.md`,
    `find ${note} -delete`,
    `find ${root} -name "*.md" -delete`,
    `find . -fprint ${note}/list`,
    // git
    `git -C ${root} checkout -- .note/a.md`,
    `git -C ${root} restore .`,
    `git -C ${root} rm -r .note`,
    `git -C ${root} clean -fdx`,
    `git -C ${root} mv .note/a.md b.md`,
    `git diff --output=${note}/p.diff`,
    // 複合指令、子殼層、替換
    `ls; echo x > ${note}/a.md`,
    `true && echo x > ${note}/a.md`,
    `false || echo x > ${note}/a.md`,
    `ls | tee ${note}/a.md`,
    `sleep 1 & echo x > ${note}/a.md`,
    `echo ok\necho x > ${note}/a.md`,
    `(cd ${root} && touch .note/c.md)`,
    `echo $(echo x > ${note}/a.md)`,
    `echo "$(touch ${note}/a.md)"`,
    `echo \`touch ${note}/a.md\``,
    `cat <(touch ${note}/a.md)`,
    `x=$(tee ${note}/a.md < /dev/null)`,
    `if true; then rm ${note}/a.md; fi`,
    `for f in a; do touch ${note}/$f; done`,
    `cat <<EOF\n$(touch ${note}/a.md)\nEOF`,
    `echo $((touch ${note}/a.md) )`,
    `echo x > "$(echo ${note}/a.md)"`,
    `rm -rf "$(dirname ${note}/a.md)"`,
    // cd 與相對路徑
    `cd ${root} && echo x > .note/a.md`,
    `cd ${root}; echo x > .note/a.md`,
    `cd ${note} && touch new.md`,
    `cd /tmp && cd ${root} && rm -rf .note`,
    `pushd ${root} && touch .note/a.md`,
    // 包裝指令
    `sudo tee ${note}/a.md < /dev/null`,
    `env FOO=1 touch ${note}/a.md`,
    `env -C ${root} touch .note/a.md`,
    `nice -n 5 rm ${note}/a.md`,
    `timeout 5 cp src.md ${note}/a.md`,
    `xargs rm ${note}/a.md < /dev/null`,
    // 直譯器與無法分類指令
    `python -c "open('${note}/a.md','w')"`,
    `python3 -c 'import os; os.remove("${note}/a.md")'`,
    `bash -c 'echo x > ${note}/a.md'`,
    `sh -c "rm ${note}/a.md"`,
    `node -e "require('fs').writeFileSync('${note}/a.md','x')"`,
    `perl -i -pe s/a/b/ ${note}/a.md`,
    `npm run gen -- --out ${note}/gen`,
    `find ${root} -exec touch {} \\;`.replace(root, note),
    `sed -n "w ${note}/a.md" /etc/hosts`,
  ];
  const reads = [
    `cat ${note}/a.md`,
    `cat ${note}/a.md > /dev/null 2>&1`,
    `ls -la ${note}`,
    `grep -rn x ${note} | head -5`,
    `head -n 3 ${note}/a.md && wc -l ${note}/a.md`,
    `find ${note} -name "*.md"`,
    `cd ${root} && cat .note/a.md`,
    `git -C ${root} log -- .note`,
    `echo "${note}/a.md"`,
    `stat ${note}/a.md; du -sh ${note}`,
  ];
  return { writes, reads };
}
