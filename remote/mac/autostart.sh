#!/bin/bash
# Keep the Pixel Agents board (port 3100) and relay (port 3199) running 24x7 on this Mac.
#
# Installs two per-user LaunchAgents (~/Library/LaunchAgents/com.pixel-agents.{board,relay}.plist)
# that start at login, are relaunched 10 s after any exit, and log to ~/.pixel-agents/logs.
# No sudo needed. The macOS counterpart of remote/windows/autostart.ps1.
#
#   remote/mac/autostart.sh                 # install + start (re-run to update)
#   remote/mac/autostart.sh --status
#   remote/mac/autostart.sh --uninstall
#   remote/mac/autostart.sh --print-plist board   # show the generated plist, change nothing
#
# Options: --repo <path> (default: repo root), --node <path> (default: node on PATH),
#          --allowed-host <name> (repeatable; default: this Mac's Tailscale name).
#
# Written for the bash 3.2 that ships with macOS: no associative arrays, no mapfile.
set -euo pipefail

ACTION=install
REPO=""
NODE=""
ALLOWED_HOSTS=""
PRINT_KEY=""

die() { echo "autostart: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --install) ACTION=install ;;
    --uninstall) ACTION=uninstall ;;
    --status) ACTION=status ;;
    --print-plist) ACTION=print; PRINT_KEY="${2:-}"; shift ;;
    --repo) REPO="${2:-}"; shift ;;
    --node) NODE="${2:-}"; shift ;;
    --allowed-host) ALLOWED_HOSTS="$ALLOWED_HOSTS ${2:-}"; shift ;;
    -h|--help) sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
  shift
done

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
[ -n "$REPO" ] || REPO="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPO="$(cd "$REPO" && pwd)" || die "no such directory: $REPO"

PA_HOME="$HOME/.pixel-agents"
LOG_DIR="$PA_HOME/logs"
AGENTS_DIR="$HOME/Library/LaunchAgents"
DOMAIN="gui/$(id -u)"
# Size-capped logging wrapper. It is plain cross-platform Node; it lives under windows/ only
# because the Windows autostart came first and its installed launchers point at that path.
WRAPPER="$REPO/remote/windows/run-logged.mjs"

KEYS="board relay"
label_of() { echo "com.pixel-agents.$1"; }
plist_of() { echo "$AGENTS_DIR/$(label_of "$1").plist"; }
port_of() { if [ "$1" = board ]; then echo 3100; else echo 3199; fi; }   # 3199 unless relay.json overrides it
script_of() {
  if [ "$1" = board ]; then echo "$REPO/dist/cli.js"; else echo "$REPO/remote/relay/relay.mjs"; fi
}

# The board answers loopback Host names only, unless told otherwise. Behind Tailscale Serve (:3443,
# tailnet only) the phone sends this Mac's MagicDNS name, so allow that one. Funnel carries /ingest
# to the relay and never reaches the board, so this exposes nothing publicly.
find_tailscale() {
  if command -v tailscale >/dev/null 2>&1; then command -v tailscale
  elif [ -x /Applications/Tailscale.app/Contents/MacOS/Tailscale ]; then
    echo /Applications/Tailscale.app/Contents/MacOS/Tailscale
  fi
}
default_allowed_host() {
  local ts json
  ts="$(find_tailscale)"
  [ -n "$ts" ] && [ -n "$NODE" ] || return 0
  json="$("$ts" status --json 2>/dev/null)" || return 0
  printf '%s' "$json" | "$NODE" -e '
    let s = ""; process.stdin.on("data", (c) => (s += c)).on("end", () => {
      try { const n = JSON.parse(s).Self.DNSName || ""; process.stdout.write(n.replace(/\.$/, "")); } catch {}
    });' 2>/dev/null || true
}

args_of() {
  if [ "$1" = board ]; then
    local out="--port 3100 --no-terminal" h
    for h in $ALLOWED_HOSTS; do out="$out --allowed-host $h"; done
    echo "$out"
  else
    echo "serve"
  fi
}

xml_escape() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
xml_string() { printf '    <string>%s</string>\n' "$(xml_escape "$1")"; }

# KeepAlive=true relaunches node after ANY exit (crash or clean), ThrottleInterval spaces the
# relaunches 10 s apart, as the Windows launcher does. PATH is the installing shell's, because
# launchd starts agents with a bare /usr/bin:/bin PATH and the board runs `claude` (Ansh, the
# Manager, local sessions). The env vars drop per-hook-event debug and request lines from a
# 24x7 log.
write_plist() {
  local key="$1" log="$LOG_DIR/$1.log" arg
  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by remote/mac/autostart.sh. Re-run it to regenerate. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$(label_of "$key")</string>
  <key>ProgramArguments</key>
  <array>
EOF
  xml_string "$NODE"
  xml_string "$WRAPPER"
  xml_string "$log"
  xml_string "$(script_of "$key")"
  # Unquoted on purpose: split the argument string into words (no element contains spaces).
  for arg in $(args_of "$key"); do xml_string "$arg"; done
  cat <<EOF
  </array>
  <key>WorkingDirectory</key>
  <string>$(xml_escape "$REPO")</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>$(xml_escape "$PATH")</string>
    <key>PIXEL_AGENTS_DEBUG</key>
    <string>0</string>
    <key>PIXEL_AGENTS_LOG_LEVEL</key>
    <string>warn</string>
  </dict>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>ThrottleInterval</key>
  <integer>10</integer>
  <key>ProcessType</key>
  <string>Standard</string>
  <key>StandardOutPath</key>
  <string>$(xml_escape "$LOG_DIR/$key.launchd.log")</string>
  <key>StandardErrorPath</key>
  <string>$(xml_escape "$LOG_DIR/$key.launchd.log")</string>
</dict>
</plist>
EOF
}

is_loaded() { launchctl print "$DOMAIN/$(label_of "$1")" >/dev/null 2>&1; }
listener_pid() { lsof -nP -t -iTCP:"$1" -sTCP:LISTEN 2>/dev/null | head -n 1 || true; }

show_status() {
  local key label state pid port up
  for key in $KEYS; do
    label="$(label_of "$key")"
    if is_loaded "$key"; then
      state="$(launchctl print "$DOMAIN/$label" 2>/dev/null | awk -F'= ' '/^\tstate =/ {print $2; exit}')"
      pid="$(launchctl print "$DOMAIN/$label" 2>/dev/null | awk -F'= ' '/^\tpid =/ {print $2; exit}')"
      printf '%s: loaded, %s%s' "$label" "${state:-unknown}" "${pid:+, pid $pid}"
    elif [ -f "$(plist_of "$key")" ]; then
      printf '%s: installed but not loaded (log out and in, or re-run the installer)' "$label"
    else
      printf '%s: not installed' "$label"
    fi
    port="$(port_of "$key")"
    if [ -n "$(listener_pid "$port")" ]; then up=listening; else up="NOT listening"; fi
    printf '; port %s %s\n' "$port" "$up"
  done
  echo "Logs: $LOG_DIR"
}

stop_agent() {
  local key="$1"
  if is_loaded "$key"; then launchctl bootout "$DOMAIN/$(label_of "$key")" 2>/dev/null || true; fi
}

resolve_node() {
  [ -n "$NODE" ] || NODE="$(command -v node || true)"
  [ -n "$NODE" ] && [ -x "$NODE" ] || die "node not found on PATH; pass --node /path/to/node"
  NODE="$(cd "$(dirname "$NODE")" && pwd)/$(basename "$NODE")"
}

if [ "$ACTION" = print ]; then
  case "$PRINT_KEY" in board|relay) ;; *) die "--print-plist takes board or relay" ;; esac
  resolve_node
  [ -n "$ALLOWED_HOSTS" ] || ALLOWED_HOSTS="$(default_allowed_host)"
  write_plist "$PRINT_KEY"
  exit 0
fi

[ "$(uname -s)" = Darwin ] || die "this script is for macOS; on Windows use remote/windows/autostart.ps1"

if [ "$ACTION" = status ]; then show_status; exit 0; fi

if [ "$ACTION" = uninstall ]; then
  for key in $KEYS; do
    stop_agent "$key"
    rm -f "$(plist_of "$key")"
    echo "Removed $(label_of "$key")"
  done
  echo "Logs kept in $LOG_DIR"
  exit 0
fi

# ---- Install (default): idempotent, re-running replaces both agents ----
for key in $KEYS; do
  [ -f "$(script_of "$key")" ] || die "missing $(script_of "$key") -- run npm run build first."
done
[ -f "$WRAPPER" ] || die "missing $WRAPPER"
resolve_node
[ -n "$ALLOWED_HOSTS" ] || ALLOWED_HOSTS="$(default_allowed_host)"
mkdir -p "$LOG_DIR" "$AGENTS_DIR"

for key in $KEYS; do
  stop_agent "$key"   # free the port before replacing the agent
done
sleep 1
for key in $KEYS; do
  port="$(port_of "$key")"
  pid="$(listener_pid "$port")"
  # Something we don't manage holds the port (a board started by hand, say). launchd would
  # relaunch ours every 10 s against it, so stop here instead of killing a stranger.
  [ -z "$pid" ] || die "port $port is in use by pid $pid ($(ps -o command= -p "$pid" | cut -c1-80)). Stop it (Ctrl+C in its terminal) and re-run."
done

for key in $KEYS; do
  plist="$(plist_of "$key")"
  write_plist "$key" > "$plist"
  plutil -lint "$plist" >/dev/null || die "generated an invalid plist: $plist"
  launchctl bootstrap "$DOMAIN" "$plist"
  echo "Registered and started $(label_of "$key")"
done
[ -z "$ALLOWED_HOSTS" ] || echo "Board accepts Host:$ALLOWED_HOSTS"
sleep 3   # let both servers bind before reporting
show_status
