<#
.SYNOPSIS
  Keep the Pixel Agents board (port 3100) and relay (port 3199) running 24x7 on this PC.
.DESCRIPTION
  Registers two per-user Scheduled Tasks in \PixelAgents\ that start at logon with no
  visible window, are relaunched if they die, and log to %USERPROFILE%\.pixel-agents\logs.
  No admin rights needed.
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File remote\windows\autostart.ps1            # install + start
  powershell -NoProfile -ExecutionPolicy Bypass -File remote\windows\autostart.ps1 -Status
  powershell -NoProfile -ExecutionPolicy Bypass -File remote\windows\autostart.ps1 -Uninstall
#>
[CmdletBinding()]
param(
  [switch]$Install,     # default action
  [switch]$Uninstall,
  [switch]$Status,
  [string]$RepoPath,    # default: repo root (two levels up from this script)
  [string]$NodePath,    # default: node.exe on PATH
  [string[]]$AllowedHost # extra Host names for the board; default: this PC's Tailscale name
)
$ErrorActionPreference = 'Stop'
if ((@($Install.IsPresent, $Uninstall.IsPresent, $Status.IsPresent) -eq $true).Count -gt 1) {
  throw 'Pass only one of -Install, -Uninstall, -Status.'
}

if (-not $RepoPath) { $RepoPath = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent }
$RepoPath  = (Resolve-Path -LiteralPath $RepoPath).Path
$TaskPath  = '\PixelAgents\'
$PaHome    = Join-Path $env:USERPROFILE '.pixel-agents'
$LogDir    = Join-Path $PaHome 'logs'
$LaunchDir = Join-Path $PaHome 'autostart'
$User      = [Security.Principal.WindowsIdentity]::GetCurrent().Name   # works for local, MSA and Entra accounts

# The board answers loopback Host names only, unless told otherwise. Behind Tailscale Serve (:3443,
# tailnet only) the phone sends this PC's MagicDNS name, so allow that one. Funnel carries /ingest to
# the relay and never reaches the board, so this exposes nothing publicly.
if (-not $AllowedHost) {
  $ts = Get-Command tailscale -ErrorAction SilentlyContinue
  if ($ts) {
    try { $name = ((& $ts.Source status --json | Out-String | ConvertFrom-Json).Self.DNSName).TrimEnd('.') } catch { $name = $null }
    if ($name) { $AllowedHost = @($name) }
  }
}
$BoardArgs = '--port 3100 --no-terminal' + (($AllowedHost | ForEach-Object { " --allowed-host $_" }) -join '')

$Services = @(
  @{ Task = 'Pixel Agents Board'; Key = 'board'; Port = 3100; Args = $BoardArgs
     Script = (Join-Path $RepoPath 'dist\cli.js') },
  @{ Task = 'Pixel Agents Relay'; Key = 'relay'; Port = 3199; Args = 'serve'   # 3199 unless relay.json overrides it
     Script = (Join-Path $RepoPath 'remote\relay\relay.mjs') }
)

$Wrapper = Join-Path $RepoPath 'remote\windows\run-logged.mjs'   # size-capped logging, see that file

function Get-PaTask($s) { Get-ScheduledTask -TaskPath $TaskPath -TaskName $s.Task -ErrorAction SilentlyContinue }
function Get-Launcher($s) { Join-Path $LaunchDir "$($s.Key).vbs" }

# Stopping a task ends wscript.exe but can leave its node children holding the port,
# so also sweep our own processes by command line (launcher first, so it cannot relaunch node).
# The script path matches the wrapper and the server it runs (and older cmd.exe launchers).
function Stop-PaService($s) {
  if (Get-PaTask $s) { Stop-ScheduledTask -TaskPath $TaskPath -TaskName $s.Task -ErrorAction SilentlyContinue }
  $needles = @((Get-Launcher $s), $s.Script)
  Get-CimInstance Win32_Process -Filter "Name='wscript.exe' OR Name='cmd.exe' OR Name='node.exe'" |
    Where-Object { $cl = $_.CommandLine; $_.ProcessId -ne $PID -and $cl -and @($needles | Where-Object { $cl.Contains($_) }).Count } |
    Sort-Object { $_.Name -ne 'wscript.exe' } |
    ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }
}

# Hidden-window launcher. Why a .vbs and not `conhost.exe --headless`: wscript.exe is a GUI-subsystem
# host, so nothing ever flashes, and Run(cmd, 0, True) starts cmd/node hidden (SW_HIDE, which also skips
# the Windows Terminal handoff) and blocks until node exits. conhost --headless was tested here: it
# waits but always exits 0, hiding crashes. The launcher itself relaunches node 10s after any exit,
# because Task Scheduler's RestartOnFailure has a 1-minute floor and is not reliably triggered by a
# non-zero exit code; RestartOnFailure stays configured as the backstop if wscript itself dies.
# run-logged.mjs writes stdout+stderr to a log capped at 5 MB (plus one .1 backup) and passes the
# exit code through. The env vars drop per-hook-event debug and request lines from a 24x7 log.
function Write-Launcher($s) {
  $log = Join-Path $LogDir "$($s.Key).log"
  $cmd = '"{0}" "{1}" "{2}" "{3}" {4}' -f $NodePath, $Wrapper, $log, $s.Script, $s.Args
  $vbs = @"
' Generated by autostart.ps1 for the "$($s.Task)" task. Re-run autostart.ps1 to regenerate.
Option Explicit
Dim sh, fso, rc
Set sh = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
sh.Environment("PROCESS")("PIXEL_AGENTS_DEBUG") = "0"
sh.Environment("PROCESS")("PIXEL_AGENTS_LOG_LEVEL") = "warn"
Sub Note(msg)
  On Error Resume Next
  Dim f : Set f = fso.OpenTextFile("$log", 8, True)
  f.WriteLine "[autostart] " & Now & " " & msg
  f.Close
End Sub
Do
  Note "starting node"
  rc = sh.Run("$($cmd.Replace('"', '""'))", 0, True)
  Note "node exited with code " & rc & "; restarting in 10s"
  WScript.Sleep 10000
Loop
"@
  $path = Get-Launcher $s
  Set-Content -LiteralPath $path -Value $vbs -Encoding Unicode   # WSH reads UTF-16 with BOM; safe for any path
  $path
}

function Show-Status {
  foreach ($s in $Services) {
    $t = Get-PaTask $s
    if ($t) {
      $i = $t | Get-ScheduledTaskInfo   # LastTaskResult 0x41301 = running, 0x41303 = never run
      $line = '{0}: {1}, last run {2}, last result 0x{3:X}' -f $s.Task, $t.State, $i.LastRunTime, $i.LastTaskResult
    } else { $line = "$($s.Task): not installed" }
    try { $up = [bool](Get-NetTCPConnection -LocalPort $s.Port -State Listen -ErrorAction Stop) } catch { $up = $false }
    Write-Host ('{0}; port {1} {2}' -f $line, $s.Port, $(if ($up) { 'listening' } else { 'NOT listening' }))
  }
}

if ($Status) { Show-Status; return }

if ($Uninstall) {
  foreach ($s in $Services) {
    Stop-PaService $s
    if (Get-PaTask $s) { Unregister-ScheduledTask -TaskPath $TaskPath -TaskName $s.Task -Confirm:$false }
    Remove-Item -LiteralPath (Get-Launcher $s) -ErrorAction SilentlyContinue
    Write-Host "Removed $($s.Task)"
  }
  if ((Test-Path -LiteralPath $LaunchDir) -and -not (Get-ChildItem -LiteralPath $LaunchDir)) { Remove-Item -LiteralPath $LaunchDir }
  try { $ts = New-Object -ComObject Schedule.Service; $ts.Connect(); $ts.GetFolder('\').DeleteFolder('PixelAgents', 0) } catch { }  # only succeeds if empty
  Write-Host "Logs kept in $LogDir"
  return
}

# ---- Install (default): idempotent, re-registering replaces the old tasks ----
foreach ($s in $Services) {
  if (-not (Test-Path -LiteralPath $s.Script)) { throw "Missing $($s.Script) -- run npm run build first." }
}
if (-not (Test-Path -LiteralPath $Wrapper)) { throw "Missing $Wrapper" }
if (-not $NodePath) { $NodePath = (Get-Command node -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1).Source }
if (-not $NodePath -or -not (Test-Path -LiteralPath $NodePath)) { throw 'node.exe not found on PATH; pass -NodePath.' }
$NodePath = (Resolve-Path -LiteralPath $NodePath).Path
if (-not (Test-Path "$env:WINDIR\System32\vbscript.dll")) {
  throw 'VBScript is not installed (Settings > System > Optional features > VBSCRIPT); the hidden launcher needs it.'
}
New-Item -ItemType Directory -Force -Path $LogDir, $LaunchDir | Out-Null

# Priority 5 = normal; the default (7) would run node at below-normal CPU and I/O priority.
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartInterval (New-TimeSpan -Minutes 1) -RestartCount 999 `
  -MultipleInstances IgnoreNew -Priority 5
$principal = New-ScheduledTaskPrincipal -UserId $User -LogonType Interactive -RunLevel Limited
$trigger   = New-ScheduledTaskTrigger -AtLogOn -User $User

foreach ($s in $Services) {
  Stop-PaService $s   # free the port before replacing the task
  $vbs = Write-Launcher $s
  $action = New-ScheduledTaskAction -Execute "$env:WINDIR\System32\wscript.exe" `
    -Argument "//B //Nologo `"$vbs`"" -WorkingDirectory $RepoPath   # //B: no script-error dialogs
  Register-ScheduledTask -TaskPath $TaskPath -TaskName $s.Task -Action $action -Trigger $trigger `
    -Settings $settings -Principal $principal -Force `
    -Description "Pixel Agents $($s.Key), managed by remote\windows\autostart.ps1" | Out-Null
  Start-ScheduledTask -TaskPath $TaskPath -TaskName $s.Task
  Write-Host "Registered and started $($s.Task)"
}
Start-Sleep -Seconds 3   # let both servers bind before reporting
Show-Status
